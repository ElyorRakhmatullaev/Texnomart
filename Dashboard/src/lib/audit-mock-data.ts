function d(daysAgo: number, hours = 10, minutes = 0, seconds = 0): Date {
  const date = new Date(2026, 4, 24); // May 24, 2026
  date.setDate(date.getDate() - daysAgo);
  date.setHours(hours, minutes, seconds, Math.floor(Math.random() * 999));
  return date;
}

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

