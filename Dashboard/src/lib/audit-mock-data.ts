// ── Types ──────────────────────────────────────────────────────────────

export type AuditActionType =
  | "login"
  | "logout"
  | "create"
  | "update"
  | "delete"
  | "export"
  | "import"
  | "view"
  | "approve"
  | "reject";

export type AuditObjectType =
  | "application"
  | "client"
  | "partner"
  | "branch"
  | "user"
  | "settings";

export interface AuditChange {
  field: string;
  oldValue: string;
  newValue: string;
}

export interface AuditEntry {
  id: string;
  timestamp: Date;
  userId: string;
  userName: string;
  userRole: string;
  userAvatar?: string;
  ip: string;
  ipCity: string;
  ipCountry: string;
  userAgent: string;
  requestId: string;
  sessionId: string;
  actionType: AuditActionType;
  objectType: AuditObjectType;
  objectId: string;
  objectLabel: string;
  objectHref: string;
  changes: AuditChange[];
  oldJson?: Record<string, unknown>;
  newJson?: Record<string, unknown>;
  relatedEntryIds: string[];
}

export type SystemLogLevel = "error" | "warning" | "info" | "debug";

export interface SystemLogEntry {
  id: string;
  timestamp: Date;
  level: SystemLogLevel;
  component: string;
  message: string;
  stackTrace?: string;
}

export type IntegrationSource = "1c" | "bnpl" | "sms" | "email";
export type IntegrationDirection = "outgoing" | "incoming";

export interface IntegrationLogEntry {
  id: string;
  timestamp: Date;
  source: IntegrationSource;
  direction: IntegrationDirection;
  endpoint: string;
  statusCode: number;
  durationMs: number;
  retryCount: number;
  requestPayload: string;
  responsePayload: string;
}

export type SecurityAlertStatus = "active" | "resolved";

export interface SecurityAlert {
  id: string;
  timestamp: Date;
  severity: "critical" | "warning" | "info";
  title: string;
  description: string;
  status: SecurityAlertStatus;
  resolvedAt?: Date;
  resolvedBy?: string;
}

export interface AlertRule {
  id: string;
  trigger: string;
  threshold: number;
  unit: string;
  windowMinutes: number;
  recipients: string[];
  enabled: boolean;
}

