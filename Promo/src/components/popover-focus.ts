/**
 * `onCloseAutoFocus` для поповеров-календарей: вернуть фокус на кнопку поля,
 * только если он никуда не ушёл.
 *
 * Radix возвращает фокус на триггер уже после анимации закрытия (~350 мс после
 * выбора дня). Если за это время открыт соседний календарь (поля «С даты» /
 * «По дату» рядом), фокус уходит из него на чужую кнопку, и новый поповер
 * закрывается как «клик снаружи» — календарь мигает и пропадает. Поймано e2e
 * (users 25-3, ≈7 из 100 прогонов), воспроизводится и быстрым пользователем.
 *
 * При обычном закрытии (выбор дня, Escape) сфокусированный элемент к этому
 * моменту уже удалён вместе с поповером, фокус на `body` — возврат на кнопку
 * поля работает как прежде.
 */
export function keepFocusIfMoved(event: Event): void {
  const active = document.activeElement;
  if (active && active !== document.body) event.preventDefault();
}
